CREATE TABLE liegenschaft (
    id BIGINT PRIMARY KEY,
    bezeichnung VARCHAR(255) NOT NULL
);

CREATE TABLE gebaeude (
    id BIGINT PRIMARY KEY,
    liegenschaft_id BIGINT NOT NULL,
    kuerzel VARCHAR(2) NOT NULL,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT fk_gebaeude_liegenschaft FOREIGN KEY (liegenschaft_id) REFERENCES liegenschaft (id),
    CONSTRAINT uq_gebaeude_kuerzel UNIQUE (kuerzel)
);

CREATE TABLE mieteinheit (
    id BIGINT PRIMARY KEY,
    gebaeude_id BIGINT NOT NULL,
    bezeichnung VARCHAR(64) NOT NULL,
    wohnflaeche DECIMAL(10, 2) NOT NULL,
    rauchwarnmelder INTEGER NOT NULL,
    CONSTRAINT fk_mieteinheit_gebaeude FOREIGN KEY (gebaeude_id) REFERENCES gebaeude (id),
    CONSTRAINT uq_mieteinheit_bezeichnung UNIQUE (gebaeude_id, bezeichnung)
);

CREATE TABLE parkplatz (
    id BIGINT PRIMARY KEY,
    liegenschaft_id BIGINT NOT NULL,
    nummer INTEGER NOT NULL,
    CONSTRAINT fk_parkplatz_liegenschaft FOREIGN KEY (liegenschaft_id) REFERENCES liegenschaft (id),
    CONSTRAINT uq_parkplatz_nummer UNIQUE (liegenschaft_id, nummer)
);

CREATE TABLE natuerliche_person (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vorname VARCHAR(255) NOT NULL,
    nachname VARCHAR(255) NOT NULL
);

CREATE TABLE mieter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE mieter_person (
    mieter_id BIGINT NOT NULL,
    person_id BIGINT NOT NULL,
    CONSTRAINT pk_mieter_person PRIMARY KEY (mieter_id, person_id),
    CONSTRAINT fk_mieter_person_mieter FOREIGN KEY (mieter_id) REFERENCES mieter (id),
    CONSTRAINT fk_mieter_person_person FOREIGN KEY (person_id) REFERENCES natuerliche_person (id)
);

CREATE TABLE mietvertrag (
    id VARCHAR(160) PRIMARY KEY,
    mieteinheit_id BIGINT NOT NULL,
    mieter_id BIGINT NOT NULL,
    vertragsbeginn DATE NOT NULL,
    vertragsende DATE NOT NULL,
    kaltmiete DECIMAL(12, 2) NOT NULL,
    betriebskostenvorauszahlung DECIMAL(12, 2) NOT NULL,
    erstellt_am DATE NOT NULL,
    CONSTRAINT fk_mietvertrag_einheit FOREIGN KEY (mieteinheit_id) REFERENCES mieteinheit (id),
    CONSTRAINT fk_mietvertrag_mieter FOREIGN KEY (mieter_id) REFERENCES mieter (id)
);

