CREATE TABLE beleg (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valutadatum DATE NOT NULL,
    betrag DECIMAL(12, 2) NOT NULL,
    beschreibung VARCHAR(500),
    kostenart VARCHAR(64) NOT NULL,
    CONSTRAINT ck_beleg_kostenart CHECK (kostenart IN (
        'Grundsteuer',
        'Wartung Rauchwarnmelder',
        'Allgemeinstrom',
        'Hausreinigung',
        'Gebäudeversicherung',
        'Glasversicherung',
        'Strassenreinigung',
        'Entwässerung',
        'Müllentsorgung'
    ))
);
