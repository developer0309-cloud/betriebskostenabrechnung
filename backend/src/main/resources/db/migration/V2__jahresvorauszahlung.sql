ALTER TABLE mietvertrag DROP COLUMN kaltmiete;
ALTER TABLE mietvertrag DROP COLUMN betriebskostenvorauszahlung;

CREATE TABLE jahresvorauszahlung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mietvertrag_id VARCHAR(160) NOT NULL,
    jahr INTEGER NOT NULL,
    betrag DECIMAL(12, 2) NOT NULL,
    CONSTRAINT fk_vorauszahlung_vertrag FOREIGN KEY (mietvertrag_id) REFERENCES mietvertrag (id) ON DELETE CASCADE,
    CONSTRAINT uq_vorauszahlung_jahr UNIQUE (mietvertrag_id, jahr)
);
